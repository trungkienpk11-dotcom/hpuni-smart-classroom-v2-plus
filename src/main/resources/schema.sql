CREATE TABLE IF NOT EXISTS rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    room_type VARCHAR(50) NOT NULL,
    projector BOOLEAN NOT NULL DEFAULT FALSE,
    computers BOOLEAN NOT NULL DEFAULT FALSE
    );

-- 1. Bảng giảng viên
CREATE TABLE IF NOT EXISTS teachers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(120) NOT NULL UNIQUE
    );

-- 2. Bảng lớp sinh viên
CREATE TABLE IF NOT EXISTS student_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    student_count INTEGER NOT NULL
    CHECK (student_count > 0)
    );

-- 3. Bảng môn học
CREATE TABLE IF NOT EXISTS courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    credits INTEGER NOT NULL
    CHECK (credits BETWEEN 1 AND 10)
    );

-- 4. Bảng lớp học phần
CREATE TABLE IF NOT EXISTS course_offerings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    course_id BIGINT NOT NULL,
    teacher_id BIGINT NOT NULL,
    group_id BIGINT NOT NULL,

    semester VARCHAR(10) NOT NULL,
    academic_year VARCHAR(20) NOT NULL,

    sessions_per_week INTEGER NOT NULL
    CHECK (sessions_per_week BETWEEN 1 AND 7),

    CONSTRAINT fk_offering_course
    FOREIGN KEY (course_id)
    REFERENCES courses(id),

    CONSTRAINT fk_offering_teacher
    FOREIGN KEY (teacher_id)
    REFERENCES teachers(id),

    CONSTRAINT fk_offering_group
    FOREIGN KEY (group_id)
    REFERENCES student_groups(id),

    CONSTRAINT uq_offering_group_course_term
    UNIQUE (
               course_id,
               group_id,
               semester,
               academic_year
           )
    );

-- BẢNG THỜI KHÓA BIỂU
CREATE TABLE IF NOT EXISTS schedule_sessions (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    offering_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,

    session_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,

     CONSTRAINT fk_schedule_offering
    FOREIGN KEY (offering_id)
    REFERENCES course_offerings(id),

    CONSTRAINT fk_schedule_room
    FOREIGN KEY (room_id)
    REFERENCES rooms(id),

    CONSTRAINT chk_schedule_time
    CHECK (start_time < end_time)
    );

-- Tăng tốc truy vấn lịch theo ngày
CREATE INDEX IF NOT EXISTS idx_schedule_date
    ON schedule_sessions(session_date);

-- Tăng tốc tìm lịch theo phòng và ngày
CREATE INDEX IF NOT EXISTS idx_schedule_room_date
    ON schedule_sessions(room_id, session_date);

--  LICH BAN GIANG VIEN

CREATE TABLE IF NOT EXISTS teacher_unavailability (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    teacher_id BIGINT NOT NULL,
    unavailable_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    reason VARCHAR(200),

    CONSTRAINT fk_busy_teacher
    FOREIGN KEY (teacher_id)
    REFERENCES teachers(id),

    CONSTRAINT chk_busy_time
    CHECK (start_time < end_time)
    );

CREATE INDEX IF NOT EXISTS idx_teacher_busy_date
    ON teacher_unavailability(teacher_id, unavailable_date);

--  YEU CAU THIET BI CUA MON HOC

CREATE TABLE IF NOT EXISTS course_room_requirements (

    course_id BIGINT PRIMARY KEY,

    needs_computers BOOLEAN NOT NULL DEFAULT FALSE,
    needs_projector BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_requirement_course
    FOREIGN KEY (course_id)
    REFERENCES courses(id)
    );
